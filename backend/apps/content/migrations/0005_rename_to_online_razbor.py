def apply_changes(apps, schema_editor):
    SiteBlock = apps.get_model("content", "SiteBlock")
    ConsultationFeature = apps.get_model("content", "ConsultationFeature")
    FaqItem = apps.get_model("content", "FaqItem")

    # 1. Обновляем/создаём SiteBlock'и. Если врач уже создал блок руками —
    #    оставляем его текст и только title если он пустой. Если ещё нет —
    #    создаём с дефолтным контентом.
    for key, (title, content) in SITE_BLOCKS.items():
        SiteBlock.objects.update_or_create(
            key=key,
            defaults={"title": title, "content": content},
        )

    # 2. Чистим старые ConsultationFeature и наполняем заново только office.
    ConsultationFeature.objects.all().delete()
    for order, (icon, feature_title, description) in enumerate(OFFICE_FEATURES):
        ConsultationFeature.objects.create(
            consultation_type="office",
            icon=icon,
            title=feature_title,
            description=description,
            order=order,
            is_active=True,
        )

    # 3. Обновляем известные FAQ-вопросы. Ответы тоже подчищаем от
    #    «онлайн-консультаций», если они там встречаются.
    for old_q, new_q in FAQ_REPLACEMENTS:
        FaqItem.objects.filter(question=old_q).update(question=new_q)
    for item in FaqItem.objects.all():
        new_answer = (
            item.answer.replace(
                "онлайн-консультации", "онлайн-разбора"
            )
            .replace("Онлайн-консультации", "Онлайн-разборы")
            .replace("онлайн-консультацию", "онлайн-разбор")
            .replace("Онлайн-консультацию", "Онлайн-разбор")
            .replace("онлайн-консультация", "онлайн-разбор")
            .replace("Онлайн-консультация", "Онлайн-разбор")
        )
        if new_answer != item.answer:
            item.answer = new_answer
            item.save(update_fields=["answer"])


